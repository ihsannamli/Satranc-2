// SAN normalizasyonu: taş için dosya/satır ayrımını atar ("Nbd2" -> "Nd2"),
// piyon terfilerini ("e8=Q" -> "Pe8Q") tek biçime indirger. Böylece tablodaki
// kısaltmalarla oyunun ürettiği SAN'lar güvenilir biçimde karşılaştırılabilir.
function normalizeSan(san) {
    if (san === 'O-O') return 'O-O'
    if (san === 'O-O-O') return 'O-O-O'

    const piece = /^([NBRQK])[a-h]?[1-8]?(x?)([a-h][1-8])(=?[qrbn])?$/.exec(san)
    if (piece) return piece[1] + piece[2] + piece[3] + (piece[4] || '')

    const pawn = /^([a-h])[1-8](x?)([a-h][1-8])(=?[qrbn])?$/.exec(san)
    if (pawn) return 'P' + pawn[2] + pawn[3] + (pawn[4] || '')

    return san
}

// En uzun eşleşen öneki döndürür. Eşleşen satır yoksa null.
function detectOpening(sanMoves) {
    const moves = sanMoves.map(normalizeSan)
    let best = null
    let bestLen = 0

    for (let i = 0; i < OPENINGS.length; i++) {
        const line = OPENINGS[i][0].split(' ').map(normalizeSan)
        if (line.length <= moves.length && line.length > bestLen) {
            let ok = true
            for (let j = 0; j < line.length; j++) {
                if (line[j] !== moves[j]) { ok = false; break }
            }
            if (ok) {
                bestLen = line.length
                best = { name: OPENINGS[i][1], eco: OPENINGS[i][2], plies: line.length }
            }
        }
    }
    return best
}
